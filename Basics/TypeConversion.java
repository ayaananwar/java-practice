package Basic;
public class TypeConversion {
    
    public static void main(String args[]){

        int a = 10;
        double b = 3.5;

        System.out.println(a/b);
        System.out.println(a+b);
        int conb = (int)b;
        double cona = (double)a;
        System.out.println(conb);
        System.out.println(cona);

    }
}
